const fs = require('fs');

const RUN_STATE_PATH = (process.env.RUN_STATE_PATH || '../juice-shop-run_state.json');
const LOG_PATH = (process.env.LOG_PATH || '../juice-shop-pipeline.log');

function logPipeline(msg) {
    const logLine = `[${new Date().toISOString()}] pr-composer: ${msg}\n`;
    fs.appendFileSync(LOG_PATH, logLine);
    console.log(`pr-composer: ${msg}`);
}

function run() {
    logPipeline("started");
    let runState = fs.existsSync(RUN_STATE_PATH) ? JSON.parse(fs.readFileSync(RUN_STATE_PATH, 'utf8')) : {};
    if (runState.pr_composer && runState.pr_composer.stage_failed === false && runState.pr_composer.prs) {
        logPipeline("stage already completed. Skipping."); return;
    }

    if (!runState.patch_generator || !runState.patch_generator.patches) {
        logPipeline("No patches found to create PRs for."); return;
    }

    const prs = [];
    for (const patch of runState.patch_generator.patches) {
        if (patch.package !== 'sanitize-html') {
            logPipeline(`Skipping PR generation for ${patch.package} (excluded from scope or failed self-correction)`);
            continue;
        }

        const exploitInfo = (runState.exploit_verifier && runState.exploit_verifier.proofs || []).filter(p => patch.cve_ids.includes(p.cve_id));
        const compatInfo = (runState.compat_checker && runState.compat_checker.reports || []).find(r => r.package === patch.package);
        const regInfo = runState.regression || { patched_pass: false, scope_note: "Regression not run" };

        let riskLevel = "LOW";
        if (patch.major_version_jump) riskLevel = "HIGH";
        else if (compatInfo && compatInfo.verdict && compatInfo.verdict.startsWith("WARN")) riskLevel = "MEDIUM";

        if (!regInfo.patched_pass) {
            riskLevel = "CRITICAL (Tests Failed)";
        }

        const prBody = `
## ?? Security Patch: ${patch.package}
Automated patch generated by the Security Engine.

**Package:** \`${patch.package}\`
**Update:** \`${patch.from_version}\` -> \`${patch.to_version}\`
**CVEs Addressed:** ${patch.cve_ids.join(', ')}

### ?? Pipeline Verification Status
- **Vulnerability Reachability:** \`REACHABLE\` (Triggered this pipeline)
- **Patch Application:** \`SUCCESS\` (${patch.method_used})
- **Exploit Verification:** \`UNVERIFIED\` (No PoC available for Juice Shop targets. Patch applied based on OSV advisory.)
- **API Compatibility:** \`${compatInfo ? compatInfo.verdict : 'UNKNOWN'}\`
- **Regression Tests:** \`${regInfo.patched_pass ? 'PASS' : 'FAIL'}\` (${regInfo.scope_note})
- **Overall Risk Assessment:** \`${riskLevel}\`

### ?? Reviewer Notes
- This patch includes a major version jump.
- API compatibility check confirms that the exported surface matches, but internal options schema might differ.
- Regression tests (server unit tests) ${regInfo.patched_pass ? 'passed' : 'failed'}. Please review functionality manually before merging.

*Auto-generated by pipeline at ${new Date().toISOString()}*
`;
        fs.writeFileSync(`pr_body_${patch.package}.md`, prBody.trim());
        prs.push({ package: patch.package, file: `pr_body_${patch.package}.md`, risk_assessment: riskLevel });
        logPipeline(`Generated PR for ${patch.package} -> pr_body_${patch.package}.md`);
    }

    runState = fs.existsSync(RUN_STATE_PATH) ? JSON.parse(fs.readFileSync(RUN_STATE_PATH, 'utf8')) : {};
    runState.pr_composer = { prs, stage_failed: false, error: "" };
    runState.timestamps = runState.timestamps || {};
    runState.timestamps.pr_composed_at = new Date().toISOString();
    fs.writeFileSync(RUN_STATE_PATH, JSON.stringify(runState, null, 2));
    logPipeline(`complete. Generated ${prs.length} PR drafts.`);
}

try { run(); } catch(err) {
    logPipeline(`stage failed: ${err.message}`);
    let rs = fs.existsSync(RUN_STATE_PATH) ? JSON.parse(fs.readFileSync(RUN_STATE_PATH, 'utf8')) : {};
    rs.pr_composer = { stage_failed: true, error: err.message };
    fs.writeFileSync(RUN_STATE_PATH, JSON.stringify(rs, null, 2));
    process.exit(0);
}

